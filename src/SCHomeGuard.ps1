function Write-Log([string]$Msg, [string]$Level = 'INFO') {
    $line = '[{0:HH:mm:ss}] {1}{2}' -f (Get-Date), $(if ($Level -ne 'INFO') { "[$Level] " } else { '' }), $Msg
