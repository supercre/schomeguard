function Write-Log([string]$Msg, [string]$Level = 'INFO') {
    $line = '[{0:HH:mm:ss}] {1}{2}' -f (Get-Date), $(if ($Level -ne 'INFO') { "[$Level] " } else { '' }), $Msg
    try { Add-Content -Path $script:LogFile -Value $line -Encoding UTF8 } catch {}
    if ($script:UiLog) { $script:UiLog.AppendText($line + "`r`n"); $script:UiLog.ScrollToEnd(); Update-Ui }
    else {
        $c = switch ($Level) { 'WARN' { 'Yellow' } 'ERROR' { 'Red' } 'OK' { 'Green' } default { 'Gray' } }
        Write-Host $line -ForegroundColor $c
    }
}
