function Remove-LegacyHosts {
    # v1.0이 hosts 파일에 넣었던 차단 구역을 지운다(v1.1부터 hosts는 쓰지 않음 — Windows가 되돌리는 경우가 있어서)
    try {
        $lines = @(Get-Content -LiteralPath $HostsFile -Encoding Default -ErrorAction Stop)
        if (-not ($lines | Where-Object { $_ -like '# >>> SCHomeGuard *' })) { return }
        $fi = Get-Item -LiteralPath $HostsFile -Force
        if ($fi.IsReadOnly) { $fi.IsReadOnly = $false }
        $out = New-Object System.Collections.Generic.List[string]; $skip = $false
        foreach ($l in $lines) {
            if ($l -like '# >>> SCHomeGuard *') { $skip = $true; continue }
            if ($l -like '# <<< SCHomeGuard *') { $skip = $false; continue }
            if (-not $skip) { $out.Add($l) }
        }
        while ($out.Count -gt 0 -and $out[$out.Count - 1] -eq '') { $out.RemoveAt($out.Count - 1) }
        [IO.File]::WriteAllLines($HostsFile, $out.ToArray(), [Text.Encoding]::ASCII)
        & ipconfig.exe /flushdns | Out-Null
        Write-Log '이전 버전(v1.0)이 hosts 파일에 넣은 차단 항목을 정리했습니다.' 'OK'
    } catch { Write-Log "hosts 정리 실패: $($_.Exception.Message)" 'WARN' }
}
function Set-SiteBlock([bool]$Enable) {
    $sites = @(Get-RiskSites | ForEach-Object { $_.Domain })
    $prev = @((Get-State).SiteBlockDomains)
    # 끌 때, 또는 목록에서 빠진 도메인: 우리가 넣었던 것만 지운다
    $SoftonicDomains = $(if ($Enable) { $sites } else { @($sites + $prev | Sort-Object -Unique) })
    $stale = @($prev | Where-Object { $_ -and $sites -notcontains $_ })
    foreach ($b in $BrowserPolicy.Keys) {
        $k = $BrowserPolicy[$b]
        if ($Enable -and $stale.Count -and (Test-Path $k)) {
            $item = Get-Item -LiteralPath $k
            foreach ($n in $item.GetValueNames()) { if ($stale -contains "$($item.GetValue($n))") { Remove-ItemProperty -LiteralPath $k -Name $n -Force } }
        }
    }
    foreach ($b in $BrowserPolicy.Keys) {
        $k = $BrowserPolicy[$b]
        if ($Enable) {
            if (-not (Test-Path $k)) { New-Item -Path $k -Force | Out-Null }
            $item = Get-Item -LiteralPath $k
            $existing = @($item.GetValueNames() | ForEach-Object { "$($item.GetValue($_))" })
            $idx = (@($item.GetValueNames() | Where-Object { $_ -match '^\d+$' } | ForEach-Object { [int]$_ }) + 0 | Measure-Object -Maximum).Maximum
            foreach ($dm in $SoftonicDomains) { if ($existing -notcontains $dm) { $idx++; New-ItemProperty -Path $k -Name "$idx" -Value $dm -PropertyType String -Force | Out-Null } }
        } elseif (Test-Path $k) {
            $item = Get-Item -LiteralPath $k
            foreach ($n in $item.GetValueNames()) { if ($SoftonicDomains -contains "$($item.GetValue($n))") { Remove-ItemProperty -LiteralPath $k -Name $n -Force } }
        }
    }
    $ffPatterns = @(); foreach ($dm in $SoftonicDomains) { $ffPatterns += "*://$dm/*", "*://*.$dm/*" }
    if ($Enable) {
        if (-not (Test-Path $FirefoxBlockKey)) { New-Item -Path $FirefoxBlockKey -Force | Out-Null }
        $item = Get-Item -LiteralPath $FirefoxBlockKey
        $existing = @($item.GetValueNames() | ForEach-Object { "$($item.GetValue($_))" })
        $idx = (@($item.GetValueNames() | Where-Object { $_ -match '^\d+$' } | ForEach-Object { [int]$_ }) + 0 | Measure-Object -Maximum).Maximum
        foreach ($p in $ffPatterns) { if ($existing -notcontains $p) { $idx++; New-ItemProperty -Path $FirefoxBlockKey -Name "$idx" -Value $p -PropertyType String -Force | Out-Null } }
    } elseif (Test-Path $FirefoxBlockKey) {
        $item = Get-Item -LiteralPath $FirefoxBlockKey
        foreach ($n in $item.GetValueNames()) { if ($ffPatterns -contains "$($item.GetValue($n))") { Remove-ItemProperty -LiteralPath $FirefoxBlockKey -Name $n -Force } }
    }
    Set-StateValue 'SiteBlockDomains' $(if ($Enable) { $sites } else { @() })
    Write-Log ("위험 사이트 차단 {0}: {1}개 도메인, 브라우저 정책(Chrome·Edge·Whale·Brave·Firefox)" -f $(if ($Enable) { '적용' } else { '해제' }), $SoftonicDomains.Count) 'OK'
    if ($Enable) { Write-Log '  브라우저를 다시 열면 적용됩니다. 브라우저에 "조직에서 관리" 표시가 생길 수 있습니다(정상).' }
}
function Test-SiteBlock {
    $k = $BrowserPolicy['Chrome']
    if (-not (Test-Path $k)) { return $false }
