function Get-UninstallCommand($Data) {
    $u = "$($Data.Quiet)"; if (-not $u) { $u = "$($Data.Uninstall)" }
    if (-not $u) { return $null }
    if ($u -match '(?i)msiexec') {
        if ($u -match '(\{[0-9A-Fa-f\-]{36}\})') { return @{ File = 'msiexec.exe'; Args = "/x $($Matches[1]) /qn /norestart" } }
        return $null
    }
    if ($u -match '^\s*"([^"]+)"\s*(.*)$') { $exe = $Matches[1]; $rest = $Matches[2] } elseif ($u -match '^\s*(\S+\.exe)\s*(.*)$') { $exe = $Matches[1]; $rest = $Matches[2] } else { return $null }
    if (-not (Test-Path -LiteralPath $exe)) { return $null }
    if ($Data.Quiet) { return @{ File = $exe; Args = $rest } }
    if ([IO.Path]::GetFileName($exe) -match '(?i)^unins\d+\.exe$') { return @{ File = $exe; Args = "$rest /VERYSILENT /SUPPRESSMSGBOXES /NORESTART".Trim() } }
    return @{ File = $exe; Args = "$rest /S".Trim() }
}
function Backup-RegKey([string]$PsPath, [string]$Tag) {
    $native = ($PsPath -replace '^Microsoft\.PowerShell\.Core\\Registry::', '' -replace '^Registry::', '' -replace '^HKLM:', 'HKEY_LOCAL_MACHINE')
    $file = Join-Path $BackupDir ('{0:yyyyMMdd_HHmmss}_{1}.reg' -f (Get-Date), ($Tag -replace '[^\w\.-]', '_'))
    & reg.exe export $native $file /y 2>$null | Out-Null
    return $file
}
function Stop-ByPath([string]$Folder) {
    foreach ($p in Get-CimInstance Win32_Process -ErrorAction SilentlyContinue | Where-Object { $_.ExecutablePath -and $_.ExecutablePath -like "$Folder*" }) {
        try { Stop-Process -Id $p.ProcessId -Force -ErrorAction Stop; Write-Log "  종료: $($p.Name) (PID $($p.ProcessId))" } catch {}
    }
}
function Save-Quarantine([string]$Path) {
    try {
        $size = (Get-ChildItem -LiteralPath $Path -Recurse -File -Force -ErrorAction SilentlyContinue | Measure-Object Length -Sum).Sum
        if ($size -gt 300MB) { Write-Log "  (백업 생략: 300MB 초과) $Path" 'WARN'; return }
        $zip = Join-Path $QuarDir ('{0:yyyyMMdd_HHmmss}_{1}.zip' -f (Get-Date), ((Split-Path $Path -Leaf) -replace '[^\w\.-]', '_'))
        Compress-Archive -LiteralPath $Path -DestinationPath $zip -Force -ErrorAction Stop
    } catch { Write-Log "  (백업 실패, 계속 진행) $($_.Exception.Message)" 'WARN' }
}
function Invoke-Clean($Items, [bool]$RestorePoint = $true) {
    $items = @($Items | Sort-Object Order)
    $keep = @($items | Where-Object { $_.Kind -eq '랜섬웨어 흔적' })
    if ($keep.Count) { Write-Log "랜섬웨어 흔적 $($keep.Count)건은 지우지 않습니다 — 복구에 필요할 수 있습니다. 보안관제(SOC)에 알려 주세요." 'WARN' }
    $items = @($items | Where-Object { $_.Kind -ne '랜섬웨어 흔적' })
    if ($items.Count -eq 0) { Write-Log '선택된 항목이 없습니다.' 'WARN'; return }
    Write-Log ("선택한 {0}개 항목을 제거합니다." -f $items.Count)
    if ($RestorePoint) {
        Write-Log '시스템 복원 지점을 만드는 중… (최대 1~2분)'
        try { Enable-ComputerRestore -Drive "$env:SystemDrive\" -ErrorAction SilentlyContinue; Checkpoint-Computer -Description 'SCHomeGuard 프록시웨어 제거 전' -RestorePointType MODIFY_SETTINGS -ErrorAction Stop; Write-Log '복원 지점 생성 완료' 'OK' }
        catch { Write-Log "복원 지점 생성 실패(계속 진행): $($_.Exception.Message)" 'WARN' }
        Update-Ui
    }
    Mount-UserHives
    $ok = 0; $fail = 0
    # 실행 중인 관련 프로세스는 항목 선택과 무관하게 먼저 정리(폴더 삭제가 막히지 않도록)
    foreach ($f in $items | Where-Object { $_.Kind -in '설치 폴더', '프록시 SDK 포함 앱' }) { Stop-ByPath $f.Data.Path }
    foreach ($f in $items) {
        $d = $f.Data
        try {
            switch ($f.Kind) {
                'Defender 예외' {
                    switch ($d.ExKind) { '폴더' { Remove-MpPreference -ExclusionPath $d.ExValue -ErrorAction Stop } '프로세스' { Remove-MpPreference -ExclusionProcess $d.ExValue -ErrorAction Stop } '확장자' { Remove-MpPreference -ExclusionExtension $d.ExValue -ErrorAction Stop } }
                    Write-Log "Defender 예외 삭제: $($d.ExKind) $($d.ExValue) (파일은 그대로)"
                }
                'Defender 설정' {
                    switch ($d.Fix) {
                        'RealTime' { Set-MpPreference -DisableRealtimeMonitoring $false -ErrorAction Stop }
                        'Behavior' { Set-MpPreference -DisableBehaviorMonitoring $false -ErrorAction Stop }
                        'Ioav' { Set-MpPreference -DisableIOAVProtection $false -ErrorAction Stop }
                        'Signature' { Update-MpSignature -ErrorAction Stop }
                        default { throw 'Windows 보안 앱에서 직접 켜 주세요' }
                    }
                    Write-Log "Defender 설정 복구: $($f.Target)"
                }
                '실행 중인 프로세스' { Stop-Process -Id $d.Pid -Force -ErrorAction Stop; Write-Log "종료: $($f.Target)" }
                '서비스' { Stop-Service -Name $d.Name -Force -ErrorAction SilentlyContinue; & sc.exe delete $d.Name | Out-Null; Write-Log "서비스 삭제: $($d.Name)" }
                '설치된 프로그램' {
                    $cmd = Get-UninstallCommand $d
                    if ($cmd) {
                        Write-Log "제거 프로그램 실행: $($cmd.File) $($cmd.Args)"
                        $spArgs = @{ FilePath = $cmd.File; PassThru = $true; WindowStyle = 'Hidden'; ErrorAction = 'Stop' }
                        if ($cmd.Args) { $spArgs.ArgumentList = $cmd.Args }
                        $pr = Start-Process @spArgs
                        if (-not $pr.WaitForExit(120000)) { try { $pr.Kill() } catch {}; Write-Log '  제거 프로그램이 2분 안에 끝나지 않아 중단(남은 파일은 직접 삭제)' 'WARN' }
                    }
                    if (Test-Path -LiteralPath $d.Key) { Backup-RegKey $d.Key "uninstall_$($f.Target)" | Out-Null; Remove-Item -LiteralPath $d.Key -Recurse -Force -ErrorAction Stop }
                    if ($d.Location -and (Test-Path -LiteralPath $d.Location)) { Stop-ByPath $d.Location; Save-Quarantine $d.Location; Remove-Item -LiteralPath $d.Location -Recurse -Force -ErrorAction Stop }
                    Write-Log "프로그램 제거: $($f.Target)"
                }
                '예약 작업' { Unregister-ScheduledTask -TaskName $d.Name -TaskPath $d.Path -Confirm:$false -ErrorAction Stop; Write-Log "예약 작업 삭제: $($f.Target)" }
                '자동 실행' {
                    Add-Content -Path (Join-Path $BackupDir 'run_values.txt') -Value ("{0:yyyy-MM-dd HH:mm:ss}`t{1}`t{2}`t{3}" -f (Get-Date), $d.Key, $d.Name, $d.Value) -Encoding UTF8
                    Remove-ItemProperty -LiteralPath $d.Key -Name $d.Name -Force -ErrorAction Stop; Write-Log "자동 실행 삭제: $($d.Name)"
                }
                '자동 실행 승인값' { Remove-ItemProperty -LiteralPath $d.Key -Name $d.Name -Force -ErrorAction Stop; Write-Log "승인값 삭제: $($d.Name)" }
                '방화벽 허용 규칙' { Remove-NetFirewallRule -Name $d.Name -ErrorAction Stop; Write-Log "방화벽 규칙 삭제: $($f.Target)" }
                '레지스트리 키' {
                    if (Test-Path -LiteralPath $d.Key) { $bk = Backup-RegKey $d.Key $f.Target.Split('\')[-1]; Remove-Item -LiteralPath $d.Key -Recurse -Force -ErrorAction Stop; Write-Log "레지스트리 키 삭제: $($f.Target) (백업 $bk)" }
                }
                { $_ -in '설치 폴더', '프록시 SDK 포함 앱' } {
                    if (Test-Path -LiteralPath $d.Path) { Save-Quarantine $d.Path; Remove-Item -LiteralPath $d.Path -Recurse -Force -ErrorAction Stop; Write-Log "폴더 삭제: $($d.Path)" }
                }
                { $_ -in '바로가기', '설치 파일', '오류 덤프', '사용 기록' } {
                    if (Test-Path -LiteralPath $d.Path) { Remove-Item -LiteralPath $d.Path -Recurse -Force -ErrorAction Stop; Write-Log "삭제: $($d.Path)" }
                }
                '휴지통' { Remove-Item -LiteralPath $d.R -Recurse -Force -ErrorAction SilentlyContinue; Remove-Item -LiteralPath $d.I -Force -ErrorAction Stop; Write-Log "휴지통에서 영구 삭제: $($f.Target)" }
            }
            $ok++
        } catch { $fail++; Write-Log "실패: [$($f.Kind)] $($f.Target) — $($_.Exception.Message)" 'ERROR' }
        Update-Ui
    }
    Dismount-UserHives
    Write-Log ("제거 완료: 성공 {0} / 실패 {1}. 백업: {2}" -f $ok, $fail, $DataDir) $(if ($fail) { 'WARN' } else { 'OK' })
}

