            $script:Hives += [pscustomobject]@{ Sid = $sid; Root = "Registry::HKEY_USERS\$sid"; Profile = $p.LocalPath; Mounted = $false; Name = $sid }
            continue
        }
        $dat = Join-Path $p.LocalPath 'NTUSER.DAT'
        if (-not (Test-Path -LiteralPath $dat)) { continue }
        $name = 'SCHG_' + ($sid -replace '[^0-9]', '')
        if (-not (Test-Path -LiteralPath "Registry::HKEY_USERS\$name")) { & reg.exe load "HKU\$name" "$dat" 2>$null | Out-Null }
        if (Test-Path -LiteralPath "Registry::HKEY_USERS\$name") {
            $script:Hives += [pscustomobject]@{ Sid = $sid; Root = "Registry::HKEY_USERS\$name"; Profile = $p.LocalPath; Mounted = $true; Name = $name }
        }
    }
}
function Dismount-UserHives {
    foreach ($h in @($script:Hives | Where-Object { $_.Mounted })) {
        [GC]::Collect(); [GC]::WaitForPendingFinalizers()
        & reg.exe unload "HKU\$($h.Name)" 2>$null | Out-Null
    }
}
