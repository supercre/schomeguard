                if ($s) { Add-Finding '위험' $s '휴지통' $orig "휴지통 보관: $(Join-Path $bin.FullName ('$R' + $i.Name.Substring(2)))" @{ I = $i.FullName; R = (Join-Path $bin.FullName ('$R' + $i.Name.Substring(2))) } }
            } catch {}
        }
    }
    Update-Ui

    # 12. 프록시 SDK가 들어 있는 다른 앱(의심)
    Write-Log '[12/12] 프록시 SDK를 품은 앱(의심)'
    $sdkRoots = @($env:ProgramFiles, ${env:ProgramFiles(x86)})
    foreach ($pr in $profiles) { $sdkRoots += (Join-Path $pr 'AppData\Local\Programs'), (Join-Path $pr 'AppData\Roaming'), (Join-Path $pr 'AppData\Local') }
    $flagged = @($script:Findings | Where-Object { $_.Kind -eq '설치 폴더' } | ForEach-Object { $_.Target })
    foreach ($r in $sdkRoots | Where-Object { $_ -and (Test-Path -LiteralPath $_) }) {
        foreach ($dll in Find-SdkDlls $r 3) {
            $dir = Split-Path $dll -Parent
            if ($flagged | Where-Object { $dir -like "$_*" }) { continue }
            $sig = @{ Name = "프록시 SDK ($([IO.Path]::GetFileName($dll)))"; Pat = ''; Note = '' }
            Add-Finding '의심' $sig '프록시 SDK 포함 앱' $dir "회선 공유 SDK 파일 $([IO.Path]::GetFileName($dll)) 포함 — 무료 프로그램에 끼워진 경우가 많음" @{ Path = $dir }
        }
        Update-Ui
    }
    Dismount-UserHives

    $danger = @($script:Findings | Where-Object { $_.Severity -eq '위험' }).Count
    $susp   = @($script:Findings | Where-Object { $_.Severity -eq '의심' }).Count
    if ($script:Findings.Count -eq 0) { Write-Log '검사 완료: 발견된 항목이 없습니다. 깨끗합니다.' 'OK' }
    else { Write-Log ("검사 완료: 위험 {0}건, 의심 {1}건" -f $danger, $susp) 'WARN' }
    Set-StateValue 'LastScan' @{ Time = (Get-Date).ToString('yyyy-MM-dd HH:mm'); Danger = $danger; Suspicious = $susp }
    return $script:Findings
}

