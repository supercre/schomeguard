    $item = Get-Item -LiteralPath $k
    return [bool](@($item.GetValueNames() | ForEach-Object { "$($item.GetValue($_))" }) -contains 'softonic.com')
}
function Get-BphList([bool]$Online = $true) {
    $set = New-Object 'System.Collections.Generic.HashSet[string]'
    foreach ($c in $EmbeddedBph) { [void]$set.Add($c) }
    $got = $false
    if ($Online) {
        foreach ($u in 'https://www.spamhaus.org/drop/drop_v4.json', 'https://www.spamhaus.org/drop/drop_v6.json') {
            try {
                $r = Invoke-WebRequest -Uri $u -UseBasicParsing -TimeoutSec 30 -ErrorAction Stop
                $n = 0
                foreach ($line in ($r.Content -split "`n")) { if ($line -match '"cidr"\s*:\s*"([^"]+)"') { [void]$set.Add($Matches[1]); $n++ } }
                Write-Log "  Spamhaus 최신 목록 $n개 받음 ($u)"
                if ($n -gt 100) { $got = $true }
            } catch { Write-Log "  Spamhaus 목록 받기 실패: $($_.Exception.Message)" 'WARN' }
        }
    }
    if (-not $got) { foreach ($c in $EmbeddedDrop) { [void]$set.Add($c) }; Write-Log '  내장 목록(2026-10-13 스냅샷)을 사용합니다.' 'WARN' }
    return @($set)
}
function Set-BphBlock([bool]$Enable) {
    Get-NetFirewallRule -Group 'SCHomeGuard-BPH' -ErrorAction SilentlyContinue | Remove-NetFirewallRule -ErrorAction SilentlyContinue
    Unregister-ScheduledTask -TaskName 'SCHomeGuard BPH 목록 갱신' -Confirm:$false -ErrorAction SilentlyContinue
    if (-not $Enable) { Write-Log '방탄호스팅 차단 해제: 방화벽 규칙·자동 갱신 작업 삭제' 'OK'; return }
    Write-Log '방탄호스팅·Spamhaus DROP 목록을 준비합니다.'
    $list = Get-BphList
    $chunks = [Math]::Ceiling($list.Count / 500)
    for ($i = 0; $i -lt $chunks; $i++) {
        $part = $list[($i * 500)..([Math]::Min($list.Count, ($i + 1) * 500) - 1)]
        foreach ($dir in 'Outbound', 'Inbound') {
            $nm = 'SCHomeGuard-BPH-{0}-{1:D2}' -f $dir, ($i + 1)
            $dn = '[SC 보안] 방탄호스팅 차단 ({0}) {1:D2}' -f $(if ($dir -eq 'Outbound') { '나가는' } else { '들어오는' }), ($i + 1)
            New-NetFirewallRule -Name $nm -DisplayName $dn -Group 'SCHomeGuard-BPH' -Direction $dir -Action Block -RemoteAddress $part -Profile Any -Description '방탄호스팅·Spamhaus DROP 대역 차단 (SuperCreative SOC). 해제는 SCHomeGuard에서.' -ErrorAction Stop | Out-Null
        }
        Update-Ui
    }
    Install-Self
    try {
        $act = New-ScheduledTaskAction -Execute $PsExe -Argument "-NoProfile -ExecutionPolicy Bypass -WindowStyle Hidden -File `"$InstalledScript`" -Cli -Action UpdateBPH"
        $trg = New-ScheduledTaskTrigger -Weekly -DaysOfWeek Monday -At 12:00
        $set = New-ScheduledTaskSettingsSet -StartWhenAvailable -ExecutionTimeLimit (New-TimeSpan -Minutes 30)
        Register-ScheduledTask -TaskName 'SCHomeGuard BPH 목록 갱신' -Action $act -Trigger $trg -Settings $set -User 'SYSTEM' -RunLevel Highest -Force -ErrorAction Stop | Out-Null
    } catch { Write-Log "자동 갱신 작업 등록 실패: $($_.Exception.Message)" 'WARN' }
    Set-StateValue 'BphUpdated' (Get-Date).ToString('yyyy-MM-dd HH:mm')
    Set-StateValue 'BphCount' $list.Count
    Write-Log ("방탄호스팅 차단 적용: 대역 {0}개, 방화벽 규칙 {1}개(들어오는·나가는), 매주 월요일 자동 갱신" -f $list.Count, ($chunks * 2)) 'OK'
}
function Test-BphBlock { return [bool](Get-NetFirewallRule -Group 'SCHomeGuard-BPH' -ErrorAction SilentlyContinue | Select-Object -First 1) }
function Set-PuaProtection([bool]$Enable) {
    try {
        $st = Get-State
        if ($Enable) {
            if ($null -eq $st.PuaOriginal) { Set-StateValue 'PuaOriginal' ([int](Get-MpPreference -ErrorAction Stop).PUAProtection) }
            Set-MpPreference -PUAProtection Enabled -ErrorAction Stop
        } else {
            $orig = if ($null -ne $st.PuaOriginal) { [int]$st.PuaOriginal } else { 0 }
            Set-MpPreference -PUAProtection $orig -ErrorAction Stop
        }
        $ek = 'HKLM:\SOFTWARE\Policies\Microsoft\Edge'
        if ($Enable) { if (-not (Test-Path $ek)) { New-Item -Path $ek -Force | Out-Null }; New-ItemProperty -Path $ek -Name 'SmartScreenPuaEnabled' -Value 1 -PropertyType DWord -Force | Out-Null }
        elseif (Test-Path $ek) { Remove-ItemProperty -Path $ek -Name 'SmartScreenPuaEnabled' -ErrorAction SilentlyContinue }
        Write-Log ("Defender 원치 않는 앱(PUA) 차단 {0}" -f $(if ($Enable) { '켜짐' } else { '원래대로' })) 'OK'
    } catch { Write-Log "Defender 설정 실패(다른 백신을 쓰는 경우 정상): $($_.Exception.Message)" 'WARN' }
}
function Test-PuaProtection { try { return ((Get-MpPreference -ErrorAction Stop).PUAProtection -eq 1) } catch { return $false } }
