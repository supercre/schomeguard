    $files = @($decoys | ForEach-Object { [pscustomobject][ordered]@{ '미끼 파일' = $_.Path; '상태' = $(if (-not (Test-Path -LiteralPath $_.Path)) { '없음(지워짐)' } elseif ((Get-FileHash -LiteralPath $_.Path -Algorithm SHA256).Hash -ne $_.Hash) { '바뀜' } else { '정상' }) } })
