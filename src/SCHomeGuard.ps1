function Add-Finding([string]$Sev, $Sig, [string]$Kind, [string]$Target, [string]$Detail, [hashtable]$Data) {
    $key = "$Kind|$Target"
    if ($script:Seen.ContainsKey($key)) { return }
    $script:Seen[$key] = $true
    $f = New-Object SCHomeGuard.Finding
    $f.Severity = $Sev; $f.Selected = ($Sev -eq '위험')
    $f.Product = $(if ($Sig) { $Sig.Name } else { '알 수 없음' })
    $f.Kind = $Kind; $f.Target = $Target; $f.Detail = $Detail; $f.Order = $KindOrder[$Kind]; $f.Data = $Data
    $script:Findings.Add($f)
}
function Find-SdkDlls([string]$Root, [int]$MaxDepth) {
    $out = New-Object System.Collections.Generic.List[string]
    $stack = New-Object System.Collections.Stack
    $stack.Push(@($Root, 0))
    while ($stack.Count -gt 0) {
        $item = $stack.Pop(); $dir = $item[0]; $depth = $item[1]
        try {
            foreach ($f in [IO.Directory]::EnumerateFiles($dir, '*.dll')) { if ([IO.Path]::GetFileName($f) -match $SdkDll) { $out.Add($f) } }
            if ($depth -lt $MaxDepth) { foreach ($d in [IO.Directory]::EnumerateDirectories($dir)) { $stack.Push(@($d, $depth + 1)) } }
        } catch {}
    }
    return $out
}
function Resolve-Lnk([string]$Path) {
    try { $sh = New-Object -ComObject WScript.Shell; $l = $sh.CreateShortcut($Path); return "$($l.TargetPath) $($l.Arguments)" } catch { return '' }
}

function Invoke-Scan {
    $script:Findings.Clear(); $script:Seen = @{}
    Write-Log '검사를 시작합니다.'
    Mount-UserHives
    $profiles = @(Get-ProfileDirs)
    Write-Log ("사용자 계정 {0}개, 레지스트리 하이브 {1}개를 검사합니다." -f $profiles.Count, $script:Hives.Count)

    # 1. 실행 중인 프로세스
    Write-Log '[1/14] 실행 중인 프로그램'
    foreach ($p in Get-CimInstance Win32_Process -ErrorAction SilentlyContinue) {
        $s = Get-Sig "$($p.Name) $($p.ExecutablePath)"
        if ($s) { Add-Finding '위험' $s '실행 중인 프로세스' "$($p.ExecutablePath)" "PID $($p.ProcessId) · $($p.Name)" @{ Pid = $p.ProcessId; Path = $p.ExecutablePath } }
    }
    Update-Ui

    # 2. 설치된 프로그램(제거 정보)
    Write-Log '[2/14] 설치된 프로그램 목록'
    $uk = @('HKLM:\SOFTWARE\Microsoft\Windows\CurrentVersion\Uninstall', 'HKLM:\SOFTWARE\WOW6432Node\Microsoft\Windows\CurrentVersion\Uninstall')
    foreach ($h in $script:Hives) { $uk += "$($h.Root)\Software\Microsoft\Windows\CurrentVersion\Uninstall" }
    foreach ($k in $uk) {
        foreach ($sub in Get-ChildItem -LiteralPath $k -ErrorAction SilentlyContinue) {
            $p = Get-ItemProperty -LiteralPath $sub.PSPath -ErrorAction SilentlyContinue
            if (-not $p) { continue }
            $s = Get-Sig "$($sub.PSChildName) $($p.DisplayName) $($p.Publisher) $($p.InstallLocation) $($p.UninstallString)"
            if ($s) {
                Add-Finding '위험' $s '설치된 프로그램' "$($p.DisplayName) $($p.DisplayVersion)" "제작사 $($p.Publisher) · 설치일 $($p.InstallDate) · $($p.InstallLocation)" @{ Key = $sub.PSPath; Uninstall = $p.UninstallString; Quiet = $p.QuietUninstallString; Location = $p.InstallLocation }
            }
        }
    }
    Update-Ui

    # 3. 설치 폴더
    Write-Log '[3/14] 설치 폴더'
    $bases = @($env:ProgramFiles, ${env:ProgramFiles(x86)}, $env:ProgramData, (Join-Path $env:ProgramData 'Microsoft\Windows\Start Menu\Programs'))
    foreach ($pr in $profiles) {
        foreach ($rel in 'AppData\Local', 'AppData\Local\Programs', 'AppData\Roaming', 'AppData\LocalLow', 'AppData\Roaming\Microsoft\Windows\Start Menu\Programs') { $bases += (Join-Path $pr $rel) }
    }
    foreach ($b in $bases | Where-Object { $_ -and (Test-Path -LiteralPath $_) }) {
        foreach ($d in Get-ChildItem -LiteralPath $b -Directory -Force -ErrorAction SilentlyContinue) {
            if ($d.Name -eq 'SCHomeGuard') { continue }
            $s = Get-Sig $d.Name
            if ($s) {
                $files = @(Get-ChildItem -LiteralPath $d.FullName -Recurse -File -Force -ErrorAction SilentlyContinue)
                $size = ($files | Measure-Object Length -Sum).Sum
                Add-Finding '위험' $s '설치 폴더' $d.FullName ("파일 {0}개 {1:N1}MB · 생성 {2:yyyy-MM-dd HH:mm}" -f $files.Count, ($size / 1MB), $d.CreationTime) @{ Path = $d.FullName }
            }
        }
    }
    Update-Ui

    # 4. 자동 실행(Run/RunOnce) + 승인값(StartupApproved)
    Write-Log '[4/14] 자동 실행 등록'
    $runKeys = @('HKLM:\SOFTWARE\Microsoft\Windows\CurrentVersion\Run', 'HKLM:\SOFTWARE\Microsoft\Windows\CurrentVersion\RunOnce', 'HKLM:\SOFTWARE\WOW6432Node\Microsoft\Windows\CurrentVersion\Run', 'HKLM:\SOFTWARE\WOW6432Node\Microsoft\Windows\CurrentVersion\RunOnce')
    $saKeys = @('HKLM:\SOFTWARE\Microsoft\Windows\CurrentVersion\Explorer\StartupApproved\Run', 'HKLM:\SOFTWARE\Microsoft\Windows\CurrentVersion\Explorer\StartupApproved\Run32')
    foreach ($h in $script:Hives) {
        $runKeys += "$($h.Root)\Software\Microsoft\Windows\CurrentVersion\Run", "$($h.Root)\Software\Microsoft\Windows\CurrentVersion\RunOnce"
        $saKeys += "$($h.Root)\Software\Microsoft\Windows\CurrentVersion\Explorer\StartupApproved\Run", "$($h.Root)\Software\Microsoft\Windows\CurrentVersion\Explorer\StartupApproved\Run32", "$($h.Root)\Software\Microsoft\Windows\CurrentVersion\Explorer\StartupApproved\StartupFolder"
    }
    foreach ($k in $runKeys) {
        $item = Get-Item -LiteralPath $k -ErrorAction SilentlyContinue
        if (-not $item) { continue }
        foreach ($n in $item.GetValueNames()) {
            $v = "$($item.GetValue($n))"
            $s = Get-Sig "$n $v"
            if ($s) { Add-Finding '위험' $s '자동 실행' "$($k -replace '^Registry::', '')\$n" $v @{ Key = $k; Name = $n; Value = $v } }
        }
    }
    foreach ($k in $saKeys) {
        $item = Get-Item -LiteralPath $k -ErrorAction SilentlyContinue
        if (-not $item) { continue }
        foreach ($n in $item.GetValueNames()) {
            $s = Get-Sig $n
            if ($s) { Add-Finding '위험' $s '자동 실행 승인값' "$($k -replace '^Registry::', '')\$n" '작업 관리자 시작프로그램 목록에 남은 값' @{ Key = $k; Name = $n } }
