$bc = New-Object System.Windows.Media.BrushConverter

function Set-Pill($Pill, $Text, [bool]$On) {
    $Pill.Background = $bc.ConvertFromString($(if ($On) { '#DCFCE7' } else { '#F2F4F7' }))
    $Text.Foreground = $bc.ConvertFromString($(if ($On) { '#15803D' } else { '#667085' }))
    $Text.Text = $(if ($On) { '● 켜짐' } else { '○ 꺼짐' })
}
function Update-Status {
    $s = Get-ProtectionStatus
    Set-Pill $ui.PillSoftonic $ui.StSoftonic $s.Softonic
    Set-Pill $ui.PillBph $ui.StBph $s.Bph
    Set-Pill $ui.PillPua $ui.StPua $s.Pua
}
$script:Buttons = @($ui.BtnProtectAll, $ui.BtnSoftonicOn, $ui.BtnSoftonicOff, $ui.BtnBphOn, $ui.BtnBphOff, $ui.BtnPuaOn, $ui.BtnPuaOff, $ui.BtnScan, $ui.BtnClean, $ui.BtnReport)
function Invoke-Busy([scriptblock]$Work) {
    foreach ($b in $script:Buttons) { $b.IsEnabled = $false }
    $ui.Busy.Visibility = 'Visible'; $script:Window.Cursor = [System.Windows.Input.Cursors]::Wait; Update-Ui
    try { & $Work } catch { Write-Log "오류: $($_.Exception.Message)" 'ERROR' }
    finally {
        foreach ($b in $script:Buttons) { $b.IsEnabled = $true }
        $ui.BtnClean.IsEnabled = ($script:Rows.Count -gt 0)
        $ui.Busy.Visibility = 'Hidden'; $script:Window.Cursor = $null
        Update-Status
    }
}
function Show-Results {
    $script:Rows.Clear()
    foreach ($f in ($script:Findings | Sort-Object @{ e = { if ($_.Severity -eq '위험') { 0 } else { 1 } } }, Product, Order)) {
        if ($f.Severity -eq '의심') { $f.Selected = [bool]$ui.ChkSusp.IsChecked }
        $script:Rows.Add($f)
    }
    $d = @($script:Rows | Where-Object { $_.Severity -eq '위험' }).Count; $s = @($script:Rows | Where-Object { $_.Severity -eq '의심' }).Count
    if ($script:Rows.Count -eq 0) {
        $ui.TxtSummary.Text = '✓ 발견된 항목이 없습니다'; $ui.SummaryBox.Background = $bc.ConvertFromString('#DCFCE7'); $ui.TxtSummary.Foreground = $bc.ConvertFromString('#15803D')
    } else {
        $prods = ($script:Rows | Where-Object { $_.Severity -eq '위험' } | Select-Object -ExpandProperty Product -Unique) -join ', '
        $ui.TxtSummary.Text = "위험 $d · 의심 $s" + $(if ($prods) { "  —  $prods" } else { '' })
        $ui.SummaryBox.Background = $bc.ConvertFromString($(if ($d) { '#FEE4E2' } else { '#FEF0C7' })); $ui.TxtSummary.Foreground = $bc.ConvertFromString($(if ($d) { '#B42318' } else { '#B54708' }))
    }
    $ui.BtnClean.IsEnabled = ($script:Rows.Count -gt 0)
}

