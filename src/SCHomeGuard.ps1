            }
        }
        foreach ($f in Get-ChildItem -LiteralPath (Join-Path $pr 'AppData\Local\CrashDumps') -File -Force -ErrorAction SilentlyContinue) {
            $s = Get-Sig $f.Name
            if ($s) { Add-Finding '위험' $s '오류 덤프' $f.FullName ("{0:yyyy-MM-dd HH:mm}" -f $f.CreationTime) @{ Path = $f.FullName } }
