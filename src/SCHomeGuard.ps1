        }
    }
    Update-Ui

    # 10. 설치 파일·사용 기록·오류 덤프
    Write-Log '[10/12] 설치 파일·사용 기록·오류 덤프'
    foreach ($pr in $profiles) {
        foreach ($rel in 'Downloads', 'Desktop') {
            foreach ($f in Get-ChildItem -LiteralPath (Join-Path $pr $rel) -File -Force -ErrorAction SilentlyContinue | Where-Object { $_.Extension -in '.exe', '.msi', '.zip' }) {
                $s = Get-Sig $f.Name
                if ($s) {
                    $sig = Get-AuthenticodeSignature -LiteralPath $f.FullName -ErrorAction SilentlyContinue
                    Add-Finding '위험' $s '설치 파일' $f.FullName ("{0:N0}B · {1:yyyy-MM-dd HH:mm} · 서명 {2}" -f $f.Length, $f.CreationTime, $sig.SignerCertificate.Subject) @{ Path = $f.FullName }
                }
            }
        }
        foreach ($f in Get-ChildItem -LiteralPath (Join-Path $pr 'AppData\Local\CrashDumps') -File -Force -ErrorAction SilentlyContinue) {
            $s = Get-Sig $f.Name
            if ($s) { Add-Finding '위험' $s '오류 덤프' $f.FullName ("{0:yyyy-MM-dd HH:mm}" -f $f.CreationTime) @{ Path = $f.FullName } }
        }
        foreach ($d in Get-ChildItem -LiteralPath (Join-Path $pr 'AppData\Local\IsolatedStorage') -Directory -Recurse -Depth 2 -Force -ErrorAction SilentlyContinue | Where-Object { $_.Name -like 'Url.*' }) {
            $id = Join-Path $d.FullName 'identity.dat'
            if (Test-Path -LiteralPath $id) {
                $b = [IO.File]::ReadAllBytes($id)
                $s = Get-Sig ([Text.Encoding]::UTF8.GetString($b) + [Text.Encoding]::Unicode.GetString($b))
                if ($s) { Add-Finding '위험' $s '사용 기록' $d.FullName '.NET IsolatedStorage(사용 통계 저장소)' @{ Path = $d.FullName } }
            }
        }
    }
    foreach ($w in 'ReportArchive', 'ReportQueue') {
        foreach ($d in Get-ChildItem -LiteralPath (Join-Path $env:ProgramData "Microsoft\Windows\WER\$w") -Directory -Force -ErrorAction SilentlyContinue) {
            $s = Get-Sig $d.Name
            if ($s) { Add-Finding '위험' $s '오류 덤프' $d.FullName 'Windows 오류 보고서' @{ Path = $d.FullName } }
        }
    }
    Update-Ui

    # 11. 휴지통
    Write-Log '[11/12] 휴지통'
    foreach ($bin in Get-ChildItem -LiteralPath "$env:SystemDrive\`$Recycle.Bin" -Directory -Force -ErrorAction SilentlyContinue) {
        foreach ($i in Get-ChildItem -LiteralPath $bin.FullName -Force -Filter '$I*' -ErrorAction SilentlyContinue) {
            try {
                $b = [IO.File]::ReadAllBytes($i.FullName)
                $orig = if ([BitConverter]::ToInt64($b, 0) -ge 2) { [Text.Encoding]::Unicode.GetString($b, 28, $b.Length - 28).TrimEnd([char]0) } else { [Text.Encoding]::Unicode.GetString($b, 24, [Math]::Min(520, $b.Length - 24)).TrimEnd([char]0) }
